#!/usr/bin/env node

/**
 * ql.io Cross-Module Performance Testing Orchestrator
 * 
 * Runs performance tests across all modules while maintaining proper isolation.
 * Each module's performance tests run independently without cross-dependencies.
 */

const { execSync } = require('child_process');
const path = require('path');
const fs = require('fs');

// Module configuration
const MODULES = {
    compiler: {
        path: 'modules/compiler',
        name: 'Compiler',
        testCommand: 'npm run test:performance',
        hasPerformanceTests: true
    },
    engine: {
        path: 'modules/engine', 
        name: 'Engine',
        testCommand: 'npm run test:performance',
        hasPerformanceTests: true
    }
};

/**
 * Performance Test Orchestrator
 */
class PerformanceTestOrchestrator {
    constructor() {
        this.results = {};
        this.startTime = Date.now();
    }
    
    /**
     * Run performance tests for a specific module
     */
    async runModuleTests(moduleKey, moduleConfig) {
        console.log(`\n🚀 Running ${moduleConfig.name} Performance Tests...`);
        console.log('='.repeat(60));
        
        const modulePath = path.resolve(moduleConfig.path);
        
        if (!fs.existsSync(modulePath)) {
            console.log(`❌ Module path not found: ${modulePath}`);
            return { success: false, error: 'Module path not found' };
        }
        
        try {
            const startTime = Date.now();
            
            // Run the module's performance tests
            const output = execSync(moduleConfig.testCommand, {
                cwd: modulePath,
                encoding: 'utf8',
                stdio: 'inherit'
            });
            
            const duration = Date.now() - startTime;
            
            console.log(`✅ ${moduleConfig.name} tests completed in ${(duration / 1000).toFixed(2)}s`);
            
            return {
                success: true,
                duration,
                module: moduleConfig.name
            };
            
        } catch (error) {
            console.log(`❌ ${moduleConfig.name} tests failed:`, error.message);
            
            return {
                success: false,
                error: error.message,
                module: moduleConfig.name
            };
        }
    }
    
    /**
     * Generate cross-module performance summary
     */
    generateSummaryReport() {
        const reportPath = path.resolve('performance-summary.md');
        const totalDuration = Date.now() - this.startTime;
        
        const successfulModules = Object.values(this.results).filter(r => r.success);
        const failedModules = Object.values(this.results).filter(r => !r.success);
        
        const report = `# ql.io Cross-Module Performance Test Summary

## 📊 Overall Results (${new Date().toISOString()})

**Total Duration:** ${(totalDuration / 1000).toFixed(2)} seconds  
**Node.js Version:** ${process.version}  
**Platform:** ${process.platform} ${process.arch}

### 📈 Module Results
- **Total Modules:** ${Object.keys(this.results).length}
- **Successful:** ${successfulModules.length} ✅
- **Failed:** ${failedModules.length} ❌
- **Success Rate:** ${Object.keys(this.results).length > 0 ? ((successfulModules.length / Object.keys(this.results).length) * 100).toFixed(1) : 0}%

## 🔍 Detailed Results

### ✅ Successful Modules
${successfulModules.map(result => 
    `- **${result.module}**: Completed in ${(result.duration / 1000).toFixed(2)}s`
).join('\n') || '- None'}

### ❌ Failed Modules  
${failedModules.map(result =>
    `- **${result.module}**: ${result.error}`
).join('\n') || '- None'}

## 📋 Module Performance Test Coverage

${Object.entries(MODULES).map(([key, config]) => `
### ${config.name}
- **Path:** \`${config.path}\`
- **Test Command:** \`${config.testCommand}\`
- **Status:** ${this.results[key]?.success ? '✅ Passed' : '❌ Failed'}
${this.results[key]?.success ? `- **Duration:** ${(this.results[key].duration / 1000).toFixed(2)}s` : ''}
`).join('')}

## 🎯 Recommendations

${failedModules.length > 0 ? `
### 🚨 Action Required
- **Failed Tests:** ${failedModules.length} module(s) have failing performance tests
- Review individual module test outputs for specific issues
- Fix failing tests before proceeding with performance optimization
` : ''}

### 📈 Performance Monitoring
- Set up automated performance regression detection
- Establish performance budgets for each module
- Monitor performance trends over time
- Consider performance gates in CI/CD pipeline

### 🔧 Module Isolation
- Each module maintains its own performance tests
- No cross-module dependencies in performance testing
- Independent baseline management per module
- Modular performance optimization approach

---
*Generated by ql.io Cross-Module Performance Testing Framework*
*Report generated at: ${new Date().toISOString()}*
`;
        
        fs.writeFileSync(reportPath, report);
        console.log(`\n📊 Summary report generated: ${reportPath}`);
        
        return reportPath;
    }
    
    /**
     * Run all module performance tests
     */
    async runAllTests() {
        console.log('🚀 ql.io Cross-Module Performance Testing');
        console.log('🔧 Testing modules independently to maintain isolation\n');
        
        // Run tests for each module
        for (const [moduleKey, moduleConfig] of Object.entries(MODULES)) {
            if (moduleConfig.hasPerformanceTests) {
                this.results[moduleKey] = await this.runModuleTests(moduleKey, moduleConfig);
            } else {
                console.log(`⏭️ Skipping ${moduleConfig.name} (no performance tests)`);
                this.results[moduleKey] = { success: true, skipped: true, module: moduleConfig.name };
            }
        }
        
        // Generate summary report
        this.generateSummaryReport();
        
        // Print final summary
        this.printFinalSummary();
        
        // Exit with appropriate code
        const hasFailures = Object.values(this.results).some(r => !r.success);
        process.exit(hasFailures ? 1 : 0);
    }
    
    /**
     * Print final summary to console
     */
    printFinalSummary() {
        const totalDuration = Date.now() - this.startTime;
        const successfulModules = Object.values(this.results).filter(r => r.success);
        const failedModules = Object.values(this.results).filter(r => !r.success);
        
        console.log('\n' + '='.repeat(60));
        console.log('🏁 CROSS-MODULE PERFORMANCE TEST SUMMARY');
        console.log('='.repeat(60));
        
        console.log(`⏱️  Total Duration: ${(totalDuration / 1000).toFixed(2)}s`);
        console.log(`📊 Module Results: ${successfulModules.length}/${Object.keys(this.results).length} passed`);
        
        if (failedModules.length > 0) {
            console.log(`🚨 Failed Modules: ${failedModules.map(r => r.module).join(', ')}`);
        }
        
        const overallSuccess = failedModules.length === 0;
        console.log(`\n${overallSuccess ? '✅ OVERALL: PASS' : '❌ OVERALL: FAIL'}`);
        
        console.log('='.repeat(60));
    }
}

/**
 * CLI Interface
 */
function main() {
    const args = process.argv.slice(2);
    
    if (args.includes('--help')) {
        console.log(`
ql.io Cross-Module Performance Testing

Usage: node test-performance.js [options]

Options:
  --help    Show this help message

This script runs performance tests for all modules independently:
${Object.entries(MODULES).map(([key, config]) => 
    `  - ${config.name}: ${config.testCommand}`
).join('\n')}

Each module's tests run in isolation to avoid cross-dependencies.
`);
        process.exit(0);
    }
    
    const orchestrator = new PerformanceTestOrchestrator();
    orchestrator.runAllTests().catch(error => {
        console.error('💥 Orchestrator failed:', error);
        process.exit(1);
    });
}

// Run if called directly
if (require.main === module) {
    main();
}

module.exports = PerformanceTestOrchestrator;