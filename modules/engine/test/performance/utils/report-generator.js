#!/usr/bin/env node

/**
 * Performance Report Generator
 * 
 * Generates comprehensive performance reports from test results.
 * Supports multiple output formats and trend analysis.
 */

const fs = require('fs');
const path = require('path');

const REPORTS_DIR = path.join(__dirname, '../reports');
const BASELINES_DIR = path.join(__dirname, '../baselines');

/**
 * Report Generator Class
 */
class ReportGenerator {
    constructor() {
        this.ensureDirectories();
    }
    
    ensureDirectories() {
        [REPORTS_DIR, BASELINES_DIR].forEach(dir => {
            if (!fs.existsSync(dir)) {
                fs.mkdirSync(dir, { recursive: true });
            }
        });
    }
    
    /**
     * Generate comprehensive performance report
     */
    generateReport(testResults, options = {}) {
        const {
            title = 'Performance Test Report',
            format = 'markdown',
            includeCharts = false,
            includeTrends = false
        } = options;
        
        const timestamp = new Date().toISOString();
        const reportData = {
            title,
            timestamp,
            nodeVersion: process.version,
            platform: `${process.platform} ${process.arch}`,
            results: testResults,
            summary: this.generateSummary(testResults)
        };
        
        switch (format) {
            case 'markdown':
                return this.generateMarkdownReport(reportData, options);
            case 'json':
                return this.generateJsonReport(reportData, options);
            case 'html':
                return this.generateHtmlReport(reportData, options);
            default:
                throw new Error(`Unsupported format: ${format}`);
        }
    }
    
    /**
     * Generate summary statistics
     */
    generateSummary(testResults) {
        const summary = {
            totalTests: 0,
            passedTests: 0,
            failedTests: 0,
            averageLatency: 0,
            totalDuration: 0,
            memoryUsage: 0
        };
        
        Object.values(testResults).forEach(result => {
            summary.totalTests++;
            
            if (result.success !== false) {
                summary.passedTests++;
            } else {
                summary.failedTests++;
            }
            
            // Aggregate metrics if available
            if (result.statistics) {
                summary.averageLatency += result.statistics.total?.mean || 0;
                summary.memoryUsage += result.statistics.memory?.avgHeapDelta || 0;
            }
        });
        
        if (summary.totalTests > 0) {
            summary.averageLatency /= summary.totalTests;
            summary.memoryUsage /= summary.totalTests;
        }
        
        summary.successRate = summary.totalTests > 0 ? 
            (summary.passedTests / summary.totalTests) * 100 : 0;
        
        return summary;
    }
    
    /**
     * Generate Markdown report
     */
    generateMarkdownReport(reportData, options) {
        const reportPath = path.join(REPORTS_DIR, `performance-report-${Date.now()}.md`);
        
        let report = `# ${reportData.title}

## 📊 Executive Summary

**Generated:** ${reportData.timestamp}  
**Node.js Version:** ${reportData.nodeVersion}  
**Platform:** ${reportData.platform}

### 🎯 Key Metrics
- **Total Tests:** ${reportData.summary.totalTests}
- **Success Rate:** ${reportData.summary.successRate.toFixed(1)}%
- **Average Latency:** ${reportData.summary.averageLatency.toFixed(2)}ms
- **Memory Usage:** ${(reportData.summary.memoryUsage / 1024 / 1024).toFixed(2)}MB

## 📈 Detailed Results

`;

        Object.entries(reportData.results).forEach(([testName, result]) => {
            report += this.formatTestResult(testName, result);
        });

        report += `## 🎯 Performance Analysis

### ✅ Strengths
${this.identifyStrengths(reportData.results).map(s => `- ${s}`).join('\n') || '- No specific strengths identified'}

### ⚠️ Areas for Improvement
${this.identifyImprovements(reportData.results).map(i => `- ${i}`).join('\n') || '- No specific improvements needed'}

### 🚀 Recommendations
${this.generateRecommendations(reportData.results).map(r => `- ${r}`).join('\n') || '- Continue monitoring performance trends'}

---
*Generated by ql.io Performance Testing Framework*
`;

        fs.writeFileSync(reportPath, report);
        console.log(`📊 Performance report generated: ${reportPath}`);
        
        return reportPath;
    }
    
    /**
     * Format individual test result
     */
    formatTestResult(testName, result) {
        if (!result.statistics) {
            return `### ❌ ${testName}
**Status:** Failed or incomplete
**Errors:** ${result.errors?.length || 0}

`;
        }
        
        const stats = result.statistics;
        const scenario = result.scenario;
        
        let status = '✅';
        if (scenario?.expectedLatency && stats.total.p95 > scenario.expectedLatency) {
            status = '⚠️';
        }
        
        return `### ${status} ${scenario?.name || testName}

${scenario?.description ? `**Description:** ${scenario.description}\n\n` : ''}**Performance Metrics:**
- **Latency (P95):** ${stats.total.p95.toFixed(2)}ms${scenario?.expectedLatency ? ` (target: ≤${scenario.expectedLatency}ms)` : ''}
- **Latency (Mean):** ${stats.total.mean.toFixed(2)}ms
- **Throughput:** ${(1000 / stats.total.mean).toFixed(2)} ops/sec
- **Success Rate:** ${stats.successRate.toFixed(1)}%

**Breakdown:**
- **Compilation:** ${stats.compilation.p95.toFixed(2)}ms (P95)
- **Execution:** ${stats.execution.p95.toFixed(2)}ms (P95)
- **Memory Delta:** ${(stats.memory.avgHeapDelta / 1024 / 1024).toFixed(2)}MB

`;
    }
    
    /**
     * Identify performance strengths
     */
    identifyStrengths(results) {
        const strengths = [];
        
        Object.entries(results).forEach(([testName, result]) => {
            if (!result.statistics) return;
            
            const stats = result.statistics;
            const scenario = result.scenario;
            
            // Fast compilation
            if (stats.compilation.p95 < 10) {
                strengths.push(`${scenario?.name || testName}: Fast compilation (${stats.compilation.p95.toFixed(2)}ms)`);
            }
            
            // High success rate
            if (stats.successRate >= 99) {
                strengths.push(`${scenario?.name || testName}: Excellent reliability (${stats.successRate.toFixed(1)}% success)`);
            }
            
            // Low memory usage
            if (stats.memory.avgHeapDelta < 10 * 1024 * 1024) {
                strengths.push(`${scenario?.name || testName}: Low memory footprint (${(stats.memory.avgHeapDelta / 1024 / 1024).toFixed(2)}MB)`);
            }
            
            // Meeting targets
            if (scenario?.expectedLatency && stats.total.p95 <= scenario.expectedLatency) {
                strengths.push(`${scenario.name}: Meets performance target (${stats.total.p95.toFixed(2)}ms ≤ ${scenario.expectedLatency}ms)`);
            }
        });
        
        return strengths;
    }
    
    /**
     * Identify areas for improvement
     */
    identifyImprovements(results) {
        const improvements = [];
        
        Object.entries(results).forEach(([testName, result]) => {
            if (!result.statistics) {
                improvements.push(`${testName}: Test execution failed - investigate errors`);
                return;
            }
            
            const stats = result.statistics;
            const scenario = result.scenario;
            
            // Slow compilation
            if (stats.compilation.p95 > 50) {
                improvements.push(`${scenario?.name || testName}: Slow compilation (${stats.compilation.p95.toFixed(2)}ms) - consider query optimization`);
            }
            
            // Missing targets
            if (scenario?.expectedLatency && stats.total.p95 > scenario.expectedLatency) {
                const overage = ((stats.total.p95 / scenario.expectedLatency - 1) * 100).toFixed(1);
                improvements.push(`${scenario.name}: Missing performance target by ${overage}% (${stats.total.p95.toFixed(2)}ms vs ${scenario.expectedLatency}ms)`);
            }
            
            // Low success rate
            if (stats.successRate < 95) {
                improvements.push(`${scenario?.name || testName}: Low success rate (${stats.successRate.toFixed(1)}%) - investigate failures`);
            }
            
            // High memory usage
            if (stats.memory.avgHeapDelta > 50 * 1024 * 1024) {
                improvements.push(`${scenario?.name || testName}: High memory usage (${(stats.memory.avgHeapDelta / 1024 / 1024).toFixed(2)}MB) - check for leaks`);
            }
        });
        
        return improvements;
    }
    
    /**
     * Generate actionable recommendations
     */
    generateRecommendations(results) {
        const recommendations = [];
        const issues = this.identifyImprovements(results);
        
        if (issues.length === 0) {
            recommendations.push('Performance looks good! Continue regular monitoring');
            recommendations.push('Consider establishing performance budgets for new features');
            return recommendations;
        }
        
        // Compilation issues
        if (issues.some(i => i.includes('compilation'))) {
            recommendations.push('**Query Optimization**: Review and optimize slow-compiling queries');
            recommendations.push('**Caching Strategy**: Implement or improve query compilation caching');
        }
        
        // Latency issues
        if (issues.some(i => i.includes('performance target'))) {
            recommendations.push('**Performance Tuning**: Focus on execution pipeline optimization');
            recommendations.push('**Async Operations**: Convert blocking operations to async where possible');
        }
        
        // Reliability issues
        if (issues.some(i => i.includes('success rate'))) {
            recommendations.push('**Error Handling**: Improve error handling and recovery mechanisms');
            recommendations.push('**Timeout Configuration**: Review and adjust timeout settings');
        }
        
        // Memory issues
        if (issues.some(i => i.includes('memory'))) {
            recommendations.push('**Memory Management**: Investigate and fix potential memory leaks');
            recommendations.push('**Resource Cleanup**: Ensure proper cleanup of resources and connections');
        }
        
        return recommendations;
    }
    
    /**
     * Generate JSON report
     */
    generateJsonReport(reportData, options) {
        const reportPath = path.join(REPORTS_DIR, `performance-report-${Date.now()}.json`);
        
        fs.writeFileSync(reportPath, JSON.stringify(reportData, null, 2));
        console.log(`📊 JSON report generated: ${reportPath}`);
        
        return reportPath;
    }
    
    /**
     * Generate HTML report (basic implementation)
     */
    generateHtmlReport(reportData, options) {
        const reportPath = path.join(REPORTS_DIR, `performance-report-${Date.now()}.html`);
        
        const html = `<!DOCTYPE html>
<html>
<head>
    <title>${reportData.title}</title>
    <style>
        body { font-family: Arial, sans-serif; margin: 40px; }
        .summary { background: #f5f5f5; padding: 20px; border-radius: 5px; }
        .metric { display: inline-block; margin: 10px; padding: 10px; background: white; border-radius: 3px; }
        .test-result { margin: 20px 0; padding: 15px; border-left: 4px solid #ccc; }
        .pass { border-left-color: #4CAF50; }
        .fail { border-left-color: #f44336; }
        .warn { border-left-color: #ff9800; }
    </style>
</head>
<body>
    <h1>${reportData.title}</h1>
    
    <div class="summary">
        <h2>Summary</h2>
        <div class="metric">
            <strong>Total Tests:</strong> ${reportData.summary.totalTests}
        </div>
        <div class="metric">
            <strong>Success Rate:</strong> ${reportData.summary.successRate.toFixed(1)}%
        </div>
        <div class="metric">
            <strong>Average Latency:</strong> ${reportData.summary.averageLatency.toFixed(2)}ms
        </div>
    </div>
    
    <h2>Test Results</h2>
    ${Object.entries(reportData.results).map(([testName, result]) => {
        const status = result.statistics ? 'pass' : 'fail';
        return `<div class="test-result ${status}">
            <h3>${testName}</h3>
            <p>Status: ${result.statistics ? 'Pass' : 'Fail'}</p>
        </div>`;
    }).join('')}
    
    <footer>
        <p><em>Generated by ql.io Performance Testing Framework at ${reportData.timestamp}</em></p>
    </footer>
</body>
</html>`;
        
        fs.writeFileSync(reportPath, html);
        console.log(`📊 HTML report generated: ${reportPath}`);
        
        return reportPath;
    }
}

/**
 * CLI Interface
 */
function main() {
    const args = process.argv.slice(2);
    const command = args[0];
    
    if (command === 'generate') {
        console.log('To generate reports, use the ReportGenerator class programmatically');
        console.log('Example: const generator = new ReportGenerator(); generator.generateReport(results);');
    } else {
        console.log(`
ql.io Performance Report Generator

Usage: node report-generator.js generate

This utility is primarily designed for programmatic use.
Import the ReportGenerator class and call generateReport() with your test results.
`);
    }
}

// Export for programmatic use
module.exports = ReportGenerator;

// Run CLI if called directly
if (require.main === module) {
    main();
}